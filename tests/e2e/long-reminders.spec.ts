import { test, expect, _electron } from '@playwright/test'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'

test('long reminders use compact tracks and the next milestone determines month and sidebar order', async () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'calendar-e2e-long-'))
  const env = Object.fromEntries(Object.entries({ ...process.env, CALENDAR_DATA_DIR: directory, CALENDAR_AGENT_DATA_DIR: path.join(directory, 'agents'), CALENDAR_DIAGNOSTIC: '1' }).filter((entry): entry is [string, string] => entry[1] !== undefined))
  delete env.ELECTRON_RUN_AS_NODE
  const electron = await _electron.launch({ args: [process.cwd()], env })
  try {
    const page = await electron.firstWindow()
    await expect(page.locator('.grid')).toBeVisible()
    await page.clock.install({ time: new Date('2026-10-21T04:00:00Z') })
    await electron.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1920, 1032))
    await page.evaluate(async () => {
      const due = (day: string) => ({ title: `${day.slice(5)} 截止｜提交作业`, start: day, end: new Date(Date.parse(day) + 86400000).toISOString().slice(0, 10), allDay: true })
      for (const [course, deadlines] of [
        ['URBP8002', ['2026-12-10']], ['GRSC6108', ['2026-11-26']], ['RECO7097', ['2026-11-13', '2026-11-20', '2026-11-27']], ['RECO6022', ['2026-11-13', '2026-11-30']]
      ] as const) {
        await window.calendar.execute({ command: 'batch.add', args: { title: `${course} 作业 · 截止日`, events: [{ title: '持续准备', start: '2026-10-21', end: '2026-12-11', allDay: true }, ...(course === 'RECO6022' ? [due('2026-10-21')] : []), ...deadlines.map(due)] } })
      }
      await window.calendar.execute({ command: 'add', args: { title: 'Evening lecture', start: '2026-10-22T19:00:00+08:00', end: '2026-10-22T20:00:00+08:00' } })
      for (const hour of ['15', '18']) await window.calendar.execute({ command: 'add', args: { title: `November lecture ${hour}`, start: `2026-11-13T${hour}:00:00+08:00`, end: `2026-11-13T${hour}:50:00+08:00` } })
      await window.calendar.execute({ command: 'batch.add', args: { title: 'Short workshop', events: [
        { title: 'Day 1', start: '2026-10-23T09:00:00+08:00', end: '2026-10-23T18:00:00+08:00' },
        { title: 'Day 2', start: '2026-10-24T09:00:00+08:00', end: '2026-10-24T17:00:00+08:00' }
      ] } })
      await window.calendar.execute({ command: 'view', args: { date: '2026-10-21' } })
    })
    const expected = ['RECO6022 作业', 'RECO7097 作业', 'GRSC6108 作业', 'URBP8002 作业']
    await expect(page.locator('.long-reminder-name')).toHaveText(expected)
    await expect(page.locator('.long-reminder-date')).toHaveText(['10.21', '11.13', '11.26', '12.10'])
    await expect(page.locator('.long-reminder .urgency-badge')).toHaveText(['今天', '剩23天', '剩36天', '剩50天'])
    const week = page.locator('.month-week').filter({ has: page.locator('[data-date="2026-10-21"]') })
    await expect(week.locator('.long-range .span-title')).toHaveText(expected)
    await expect(week.locator('.long-range .span-time')).toHaveText(['10.21', '11.13', '11.26', '12.10'])
    await expect(week.locator('.long-range .urgency-badge')).toHaveText(['今天', '剩23天', '剩36天', '剩50天'])
    expect(await week.locator('.long-range').first().evaluate(node => getComputedStyle(node).backgroundColor)).toBe('rgba(0, 0, 0, 0)')
    const short = week.locator('.month-span:not(.long-range)')
    await expect(short.locator('.span-time')).toHaveText('10.23 09:00 — 10.24 17:00')
    expect((await week.locator('.long-range').first().boundingBox())!.height).toBeCloseTo((await short.boundingBox())!.height)
    expect(await short.evaluate(node => getComputedStyle(node).backgroundColor)).toBe('rgba(0, 0, 0, 0)')
    expect(await week.locator('.long-range .urgency-badge').first().evaluate(node => getComputedStyle(node).color)).toBe('rgb(148, 62, 50)')
    expect((await page.locator('.long-reminders').boundingBox())!.height).toBeLessThan(310)
    await expect(page.locator('.agenda-event')).toHaveCount(0)
    await page.screenshot({ path: 'test-results/long-reminders-swiss.png' })
    await page.locator('.long-reminder-row').first().click()
    await expect(page.locator('.group-title')).toHaveText('RECO6022 作业 · 截止日')
    await expect(page.locator('.timeline-day')).toHaveCount(3)
    await page.clock.setFixedTime(new Date('2026-11-11T04:00:00Z'))
    await page.evaluate(() => window.calendar.execute({ command: 'view', args: { date: '2026-11-11' } }))
    await expect(page.locator('.long-reminder .urgency-badge').first()).toHaveText('剩2天')
    await expect(page.locator('.long-reminder .urgency-badge').first()).toHaveAttribute('data-urgency', 'critical')
    const markers = page.locator('.month-milestone[data-milestone-date="2026-11-13"]')
    await expect(markers).toHaveCount(2)
    await expect(markers.first()).toHaveAttribute('title', /RECO6022.*11\.13.*提交作业/)
    await expect(markers.first()).toHaveAttribute('data-urgency', 'critical')
    const originalSubjectId = await markers.first().getAttribute('data-event-id')
    const day = await page.locator('.day[data-date="2026-11-13"]').boundingBox()
    for (const marker of await markers.all()) {
      const bounds = await marker.boundingBox()
      expect(bounds!.x).toBeGreaterThan(day!.x)
      expect(bounds!.x + bounds!.width).toBeLessThan(day!.x + day!.width)
      expect(bounds!.y).toBeGreaterThan(day!.y)
      expect(bounds!.y + bounds!.height).toBeLessThan(day!.y + day!.height)
      const ink = await marker.evaluate(node => getComputedStyle(node).color)
      await expect(marker.locator('.milestone-diamond')).toHaveCSS('background-color', ink)
      const id = await marker.getAttribute('data-event-id')
      await expect(page.locator(`.long-reminder[data-event-id="${id}"] .long-reminder-name`)).toHaveCSS('border-left-color', ink)
    }
    await expect(page.locator('.month-milestone[data-milestone-date="2026-11-20"]')).toHaveCount(1)
    await expect(page.locator('.month-milestone[data-milestone-date="2026-11-30"]')).toHaveCount(1)
    await expect(page.locator('.month-milestone[data-milestone-date="2026-11-01"]')).toHaveCount(0)
    await page.screenshot({ path: 'test-results/long-reminders-urgent.png' })
    await expect(page.locator('.long-range .span-title')).toHaveCount(4)
    await expect(page.locator('.long-range.continuation-track .span-title')).toHaveCount(0)
    await expect(page.locator('.long-range.continuation-track .span-time')).toHaveCount(0)
    expect(await page.locator('.grid').evaluate(node => node.scrollHeight - node.clientHeight)).toBeLessThanOrEqual(1)
    const gridBounds = (await page.locator('.grid').boundingBox())!, lastWeekBounds = (await page.locator('.month-week').last().boundingBox())!
    expect(lastWeekBounds.y + lastWeekBounds.height).toBeLessThanOrEqual(gridBounds.y + gridBounds.height + 1)
    await expect(page.locator('.day[data-date="2026-11-13"] .event-chip:visible')).toHaveCount(2)
    await markers.first().click()
    await expect(page.locator('.group-title')).toHaveText('RECO6022 作业 · 截止日')
    const selected = await page.evaluate(() => window.calendar.execute({ command: 'status' }))
    expect((selected as { data: { selectedDate: string } }).data.selectedDate).toBe('2026-11-13')
    await page.locator('.month-milestone[data-milestone-date="2026-11-30"]').focus()
    await page.keyboard.press('Enter')
    await expect(page.locator('.day[data-date="2026-11-30"]')).toHaveClass(/selected/)
    await page.evaluate(() => window.calendar.execute({ command: 'view', args: { date: '2026-11-21' } }))
    await expect(page.locator('.long-reminder-name')).toHaveText(['GRSC6108 作业', 'RECO7097 作业', 'RECO6022 作业', 'URBP8002 作业'])
    const laterWeek = page.locator('.month-week').filter({ has: page.locator('[data-date="2026-11-21"]') })
    await expect(laterWeek.locator('.long-range .span-title')).toHaveCount(0)
    const order = await page.locator('.long-reminder').evaluateAll(nodes => nodes.map(node => node.getAttribute('data-event-id')))
    expect(await laterWeek.locator('.long-range').evaluateAll(nodes => nodes.map(node => node.getAttribute('data-event-id')))).toEqual(order)
    await expect(page.locator('.long-reminder .urgency-badge').first()).toHaveText('剩15天')
    await expect(page.locator('.long-reminder .urgency-badge').first()).toHaveAttribute('data-urgency', 'normal')
    await page.clock.setFixedTime(new Date('2026-11-21T04:00:00Z'))
    await page.evaluate(() => window.calendar.execute({ command: 'view', args: { date: '2026-11-21' } }))
    await expect(markers.first()).toHaveAttribute('data-urgency', 'past')
    await expect(markers.first().locator('.milestone-diamond')).toHaveCSS('background-color', 'rgb(245, 242, 233)')
    await expect(page.locator(`.month-milestone[data-milestone-date="2026-11-13"][data-event-id="${originalSubjectId}"]`)).toHaveCSS('color', 'rgb(139, 116, 59)')
    // Losing another subject moves a continuation upward without changing ink.
    const removedId = await page.locator('.long-reminder').filter({ hasText: 'RECO6022 作业' }).getAttribute('data-event-id')
    const survivorId = await page.locator('.long-reminder').filter({ hasText: 'URBP8002 作业' }).getAttribute('data-event-id')
    const survivor = laterWeek.locator(`.long-range[data-event-id="${survivorId}"]`)
    const oldLane = Number(await survivor.getAttribute('data-lane'))
    const oldInk = await survivor.evaluate(node => getComputedStyle(node, '::after').backgroundColor)
    await page.evaluate(id => window.calendar.execute({ command: 'delete', args: { id, expectedVersion: 1 } }), removedId)
    await expect(survivor).toHaveAttribute('data-lane', String(oldLane - 1))
    expect(await survivor.evaluate(node => getComputedStyle(node, '::after').backgroundColor)).toBe(oldInk)
    await page.reload()
    await expect(page.locator('.grid')).toBeVisible()
    expect(await survivor.evaluate(node => getComputedStyle(node, '::after').backgroundColor)).toBe(oldInk)
    await page.clock.setFixedTime(new Date('2026-10-21T04:00:00Z'))
    await page.evaluate(async () => {
      await window.calendar.execute({ command: 'view', args: { date: '2026-10-22' } })
      await window.calendar.execute({ command: 'settings.set', args: { fontSize: 22 } })
    })
    await expect(page.locator('.app')).toHaveCSS('font-size', '22px')
    await electron.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(900, 650))
    await expect.poll(() => page.evaluate(() => window.innerWidth)).toBe(900)
    await expect(page.locator('[data-date="2026-10-22"] .event-chip')).toBeVisible()
    expect(await page.locator('.long-reminders').evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    await page.screenshot({ path: 'test-results/long-reminders-compact.png' })
  } finally {
    await electron.close()
    fs.rmSync(directory, { recursive: true, force: true })
  }
})
